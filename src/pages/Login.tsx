// src/pages/Login.tsx
// sign in or create an account, then land on the dashboard

import { useState } from "react";
import { useNavigate, useSearchParams } from "react-router-dom";
import { api, useAuth } from "../services/api";

const Login = () => {
  const { setUser } = useAuth();
  const navigate = useNavigate();
  // the landing page links straight to the create-account tab
  const [params] = useSearchParams();

  // mode switches between the two forms
  const [mode, setMode] = useState<"signin" | "register">(
    params.get("tab") === "register" ? "register" : "signin");
  const [username, setUsername] = useState("");
  const [password, setPassword] = useState("");
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(false);

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError("");
    setBusy(true);
    try {
      if (mode === "signin") {
        await api.login(username, password);
      } else {
        await api.register(username, password);
      }
      setUser(await api.me());
      navigate("/");
    } catch (err) {
      setError(err instanceof Error ? err.message : "Something went wrong");
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="auth-page">
      <div className="auth-card">
        <div className="auth-brand">
          <span className="brand-mark">F</span>
          <h1>FOKUS</h1>
        </div>
        <p className="auth-tagline">Your learning, on one track</p>

        <div className="auth-tabs" role="tablist">
          <button
            role="tab" aria-selected={mode === "signin"}
            className={`auth-tab ${mode === "signin" ? "active" : ""}`}
            onClick={() => { setMode("signin"); setError(""); }}
            type="button"
          >
            Sign in
          </button>
          <button
            role="tab" aria-selected={mode === "register"}
            className={`auth-tab ${mode === "register" ? "active" : ""}`}
            onClick={() => { setMode("register"); setError(""); }}
            type="button"
          >
            Create account
          </button>
        </div>

        <form onSubmit={submit}>
          <div className="form-field">
            <label htmlFor="username">Username</label>
            <input
              id="username"
              value={username}
              onChange={(e) => setUsername(e.target.value)}
              autoComplete="username"
              placeholder="3-24 letters, numbers or _"
            />
          </div>
          <div className="form-field">
            <label htmlFor="password">Password</label>
            <input
              id="password"
              type="password"
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              autoComplete={mode === "signin" ? "current-password" : "new-password"}
              placeholder="At least 6 characters"
            />
          </div>

          {error && <p className="error-text" role="alert">{error}</p>}

          <button className="btn-primary btn-block" type="submit" disabled={busy || !username || !password}>
            {busy ? "..." : mode === "signin" ? "Sign in" : "Create account"}
          </button>
        </form>

        <p className="auth-note">
          Roadmaps are generated by a free AI with Wikipedia research, real YouTube videos and course links
        </p>
      </div>
    </div>
  );
};

export default Login;
